// --- Заглушка для Typography ---
// Тебе нужно будет определить свой AppTypography в отдельном файле
// или прямо здесь, используя androidx.compose.material3.Typography
val AppTypography = Typography() // Используй свой реальный объект Typography здесь

@Composable
fun AppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(), // isSystemInDarkTheme() работает и для Desktop
    content: @Composable () -> Unit
) {
    // Для Compose Desktop нет динамических цветов, поэтому логика упрощается
    val colorScheme = if (darkTheme) darkScheme else lightScheme

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography, // Используем твой объект Typography
        content = content
    )
}
